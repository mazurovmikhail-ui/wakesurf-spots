function el(tag, cls, html) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (html != null) e.innerHTML = html;
  return e;
}

function renderPhysics() {
  const chipsBox = document.getElementById("physChips");
  const listBox = document.getElementById("physList");
  if (!chipsBox || !listBox) return;
  let current = "Все";

  function draw() {
    listBox.innerHTML = "";
    PHYSICS.filter(p => current === "Все" || p.g === current).forEach(p => {
      listBox.appendChild(el("article", "phys-card", `
        <h3>${p.s} <span class="phys-group">${p.g}</span></h3>
        <p class="phys-myth">✗ Миф: ${p.myth}</p>
        <p class="phys-why"><b>Физика:</b> ${p.why}</p>
        <p class="phys-fix"><b>→ Что делать:</b> ${p.fix}</p>
        <p class="phys-src">${p.src}</p>`));
    });
  }

  GROUPS.forEach(g => {
    const c = el("button", "phys-chip" + (g === "Все" ? " on" : ""), g);
    c.addEventListener("click", () => {
      current = g;
      chipsBox.querySelectorAll(".phys-chip").forEach(x => x.classList.toggle("on", x.textContent === g));
      draw();
    });
    chipsBox.appendChild(c);
  });
  draw();
}

renderPhysics();
